def _hero_frame(assets: list[Asset], run_path: Path) -> Image.Image | None:
    visual = [a for a in assets if a.kind in ("animation", "screen_recording", "image")]
    hero = next((a for a in visual if a.meta.get("hero")), visual[0] if visual else None)
    if hero is None:
        return None
    p = run_path / hero.path
    if p.suffix.lower() in (".png", ".jpg", ".jpeg"):
        return Image.open(p).convert("RGB")
    from moviepy import VideoFileClip

    clip = VideoFileClip(str(p), audio=False)
    frame = clip.get_frame(clip.duration * float(hero.meta.get("hero_at", 0.85)))
    clip.close()
    return Image.fromarray(frame)


def make_thumbnail(script: Script, assets: list[Asset], ctx: RunContext) -> Path:
    W, H = 1280, 720
    base = Image.new("RGB", (W, H), hex_rgba(theme.SURFACE)[:3])
    hero = _hero_frame(assets, ctx.run.path)
    if hero is not None:
        hero = hero.resize((W, int(hero.height * W / hero.width)))
        base.paste(hero, (0, (H - hero.height) // 2))
        # darken the left two-thirds so the words read at phone size
        shade = Image.new("L", (W, H))
        sd = ImageDraw.Draw(shade)
        for x in range(W):
            sd.line([(x, 0), (x, H)], fill=int(225 * max(0.0, 1 - x / (W * 0.72)) + 15))
        dark = Image.new("RGB", (W, H), (12, 12, 12))
        base = Image.composite(dark, base, shade.filter(ImageFilter.GaussianBlur(8)))
    d = ImageDraw.Draw(base)
    # brand badge
    bf = font(34, "bold")
    label = ctx.brand.upper()
    bw = int(bf.getlength(label)) + 36
    d.rounded_rectangle([48, 44, 48 + bw, 44 + 58], radius=10, fill=theme.ACCENT)
    d.text((66, 50), label, font=bf, fill=theme.TEXT)
    # headline: up to 3 lines, last word highlighted
    words = script.thumbnail_text.upper().split()
    size = 132
    while size > 70:
        hf = font(size, "bold")
        lines = wrap(" ".join(words), hf, int(W * 0.62))
        if len(lines) <= 3:
            break
        size -= 8
    y = H - 60 - len(lines) * int(size * 1.05)
    for i, line in enumerate(lines):
        last = i == len(lines) - 1
        d.text((52, y), line, font=hf, fill=theme.HIGHLIGHT if last else theme.TEXT,
               stroke_width=4, stroke_fill=(10, 10, 10))
        y += int(size * 1.05)
    out = ctx.run.sub("out") / "thumbnail.png"
    base.save(out, optimize=True)
    return out


def _ts(t: float) -> str:
    t = int(t)
    return f"{t // 60}:{t % 60:02d}"


def build_description(script: Script, research: ResearchPack, render: RenderOutput, assets: list[Asset],
                      voice: VoiceTrack, ctx: RunContext) -> tuple[str, bool]:
    parts = [script.summary.strip() or script.title, ""]
    chapters = render.chapters
    if len(chapters) >= 3 and all(b[0] - a[0] >= 10 for a, b in zip(chapters, chapters[1:])):
        parts.append("Chapters")
        parts += [f"{_ts(0 if i == 0 else t)} {name}" for i, (t, name) in enumerate(chapters)]
        parts.append("")
    cited = {c.source_id for seg in script.segments for c in seg.claims}
    parts.append("Sources")
    for src in research.sources:
        if src.id not in cited and src.kind not in ("dataset",):
            continue
        bits = [src.title]
        if src.publisher:
            bits.append(src.publisher)
        code_url = ctx.settings.get("channel.code_url") or ""
        if src.url:
            bits.append(src.url)
        elif src.reference and src.kind in ("computation", "build") and code_url:
            bits.append(f"{src.reference} · code: {code_url}")
        elif src.reference:
            bits.append(src.reference)
        if src.licence:
            bits.append(f"licence: {src.licence}")
        parts.append("- " + " | ".join(bits))
    parts.append("")
    parts.append("Credits & licences")
    parts.append("- Charts, animations, screen recordings and music: generated by code for this video (self-generated).")
    for a in assets:
        if a.attribution:
            parts.append(f"- {a.attribution} ({a.licence})")
    needed, reasons = requires_disclosure(CheckContext(settings=ctx.settings, voice=voice, assets=assets))
    if needed:
        parts.append(f"- {DISCLOSURE_MARKER}: the voice is synthetic (Kokoro-82M text-to-speech, "
                     f"Apache-2.0), not a real person. Script reviewed by a human before upload.")
    else:
        parts.append("- Narration recorded by the creator." if voice.backend == "recorded" else "- No synthetic voice used.")
    parts.append("")
    parts.append(f"{ctx.brand}: {ctx.settings.get('channel.tagline', '')}")
    parts.append(" ".join("#" + t.replace(" ", "") for t in script.tags[:3]))
    text = "\n".join(parts)
    return text[:4900], needed


def run_packaging(script: Script, research: ResearchPack, render: RenderOutput, assets: list[Asset],
                  voice: VoiceTrack, ctx: RunContext) -> tuple[Metadata, Asset]:
    thumb = make_thumbnail(script, assets, ctx)
    description, synthetic = build_description(script, research, render, assets, voice, ctx)
    tags, total = [], 0
    for t in [*script.tags, ctx.brand.lower(), script.format.replace("_", " ")]:
        if t not in tags and total + len(t) + 1 <= 480:
            tags.append(t)
            total += len(t) + 1
    meta = Metadata(
        title=script.title[:100], description=description, tags=tags,
        category_id=str(ctx.settings.get("channel.youtube_category_id", "28")),
        default_language=ctx.settings.get("channel.default_language", "en"),
        contains_synthetic_media=synthetic, thumbnail=str(thumb.relative_to(ctx.run.path)),
    )
    thumb_asset = Asset(id="thumbnail", segment_id=None, kind="thumbnail", path=meta.thumbnail,
                        licence="self-generated", origin="Pillow composite of a self-generated frame")
    return meta, thumb_asset
